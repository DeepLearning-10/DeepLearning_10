# 라인별 온도 평균도 출력해 근거로 삼으세요.
#
# [확인 항목]
#   - (가)는 0건이다. 멘티가 "이상 없음"이라고 판단한 이유가 여기 있다
#   - (나)에서는 0건이 아니다
#   - 걸린 값 중에 '숫자만 보면 정상 같은데 그 라인에서는 비정상'인 것이 있다. 어느 것인가
#
# [멘티에게 한 문장으로]
#   "온도 73.5도는 A라인이면 정상이지만 C라인에서는 ..."

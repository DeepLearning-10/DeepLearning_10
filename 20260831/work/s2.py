# (가) 표 전체 기준 z-score
z = (temp - temp.mean()) / temp.std(ddof=0)

# (나) 같은 생산라인 기준 z-score
z_2 = (temp - group_temp.transform("mean")) / group_temp.transform(
    lambda x: x.std(ddof=0)
)

# 이상치 조건
mask_all = z.abs() > 2.5
mask_line = z_2.abs() > 2.5

# 이상치 개수
print("\n3번 문제.")

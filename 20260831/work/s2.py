def scale_data(df, standard):
    result = df.copy()

    for col in 센서:
        low = standard.loc[col, "min"]
        high = standard.loc[col, "max"]

        # 모든 값이 같은 열일 때 0으로 처리
        if low == high:
            result[col] = 0.0
        else:
            result[col] = (result[col] - low) / (high - low)

    return result



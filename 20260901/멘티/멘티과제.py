# print(int(z[np.abs(z) > 3].sum()), int(z[np.abs(z) > 2].sum()))

# ----------------------------------------
# 문제 7. IQR로 메모리 이상 찾기
# ----------------------------------------
# 메모리 열 전체의 아래·위 울타리(임계값 1.5)를 소수 둘째 자리로 한 줄에 출력하고,
# 울타리를 벗어난 개수를 출력하세요.
# 이어서 걸린 행이 어느 구역에서 나왔는지 개수를 출력하세요.
# 힌트: 원하는 분위수(25%, 75%)를 구해 주는 메서드가 있습니다. 조건에 맞는 행만
#       골라내려면 대괄호 안에 조건식을 넣으면 됩니다. 두 조건을 잇는 기호는 | 입니다.
# 기대 출력: 1.08 59.76
#            3
#            {'Z3-찰리': 3}

q1 = np.percentile(df["메모리"], 25)
q3 = np.percentile(df["메모리"], 75)
iqr = q3 - q1
low, high = q1 - 1.5 * iqr, q3 + 1.5 * iqr
# print(round(low, 2), round(high, 2))
mask = (df["메모리"] < low) | (df["메모리"] > high)
# print(mask.sum())
dk = df[mask]
# print(dk["구역"].value_counts().to_dict())


